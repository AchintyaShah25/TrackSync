"""Fetch and parse knowledge sources. Every network response is cached on disk so
re-runs are free and tests use recorded fixtures."""

from __future__ import annotations

import hashlib
import io
import json
import logging
import re
import time
from dataclasses import dataclass, field
from pathlib import Path

import requests
from pypdf import PdfReader

log = logging.getLogger(__name__)

# A generic client name (no personal or project details sent to third parties).
USER_AGENT = "f1-analytics-etl/0.1 (unofficial, non-commercial)"
FIA_INDEX = "https://www.fia.com/regulation/category/110"
WIKI_API = "https://en.wikipedia.org/w/api.php"
LICENSES = {
    "fia": "© FIA. Excerpt quoted for reference; the official document prevails.",
    "wikipedia": "CC BY-SA 4.0 (Wikipedia contributors)",
    "summary": "Generated by TrackSync from OpenF1 (CC BY-NC-SA 4.0) and Jolpica-F1 data",
}


@dataclass
class Document:
    source: str  # fia | wikipedia | summary
    source_key: str
    title: str
    url: str | None
    sections: list[tuple[str, str]]  # (section label, text)
    season: int | None = None
    event_id: int | None = None
    license: str = field(default="")

    def __post_init__(self) -> None:
        self.license = self.license or LICENSES[self.source]

    @property
    def content_hash(self) -> str:
        blob = json.dumps([self.title, self.url, self.sections], ensure_ascii=False)
        return hashlib.sha256(blob.encode()).hexdigest()


class Fetcher:
    """GET with an on-disk cache keyed by URL (+ params), polite pacing and retries.

    Uncached requests are spaced `min_interval_s` apart and 429/503 responses are retried
    with backoff: Wikipedia throttles clients that fire many requests per second.
    """

    def __init__(
        self,
        cache_dir: Path,
        session: requests.Session | None = None,
        min_interval_s: float = 0.5,
        sleep=time.sleep,
        clock=time.monotonic,
    ):
        self.cache_dir = cache_dir
        self.session = session or requests.Session()
        self.session.headers["User-Agent"] = USER_AGENT
        self.min_interval_s = min_interval_s
        self._sleep = sleep
        self._clock = clock
        self._last = -1e9
        self.requests_made = 0
        cache_dir.mkdir(parents=True, exist_ok=True)

    def get(self, url: str, params: dict | None = None, refresh: bool = False) -> bytes:
        key = hashlib.sha256(json.dumps([url, params], sort_keys=True).encode()).hexdigest()[:24]
        path = self.cache_dir / key
        if path.exists() and not refresh:
            return path.read_bytes()
        for attempt in range(4):
            wait = self.min_interval_s - (self._clock() - self._last)
            if wait > 0:
                self._sleep(wait)
            self._last = self._clock()
            self.requests_made += 1
            resp = self.session.get(url, params=params, timeout=60)
            if resp.status_code in (429, 503) and attempt < 3:
                retry = resp.headers.get("retry-after", "")
                self._sleep(float(retry) if retry.isdigit() else 5.0 * 2**attempt)
                continue
            resp.raise_for_status()
            path.write_bytes(resp.content)
            return resp.content
        raise RuntimeError("unreachable")


# ---------------------------------------------------------------- FIA regulations

PDF_LINK = re.compile(r'href="([^"]+_f1_regulations_-_section_[^"]+\.pdf)"', re.IGNORECASE)
# Section A (general provisions: points, championship) and B (sporting: race procedures).
FIA_SECTIONS = {"A": "General Provisions", "B": "Sporting Regulations"}
ISSUE = re.compile(r"iss_?(\d+)", re.IGNORECASE)
PAGE_HEADER = re.compile(
    r"^(SECTION [A-Z]: .*|[A-Z]|0|[A-Z]\d+|\d{4} Formula 1 Regulations - Section [A-Z].*|©.*|"
    r"\d{1,2} \w+ \d{4}|Issue \d+)\s*$"
)
# Running header/footer lines that can appear anywhere on a page (Section A puts them
# mid-text), safe to drop wherever they occur.
HEADER_ANYWHERE = re.compile(
    r"^(SECTION [A-Z]: .*|\d{4} Formula 1(:| Regulations - Section).*|©\s?\d{4} F.d.ration.*|"
    r"Issue \d+|\d{1,2} \w+ \d{4})\s*$"
)
ARTICLE = re.compile(r"^([A-Z]\d+\.\d+)\s+([A-Z][^\n]{2,90})$")
MIN_SECTION_CHARS = 80


def latest_regulation_pdf(index_html: str, season: int, section: str = "B") -> str | None:
    """Newest issue of one section of the F1 regulations for `season`."""
    best: tuple[int, str] | None = None
    for url in PDF_LINK.findall(index_html):
        name = url.rsplit("/", 1)[-1].lower()
        if not name.startswith(f"fia_{season}_f1_regulations_-_section_{section.lower()}_"):
            continue
        m = ISSUE.search(name)
        issue = int(m.group(1)) if m else 0
        if best is None or issue > best[0]:
            best = (issue, url)
    return best[1] if best else None


def regulation_sections(pdf_bytes: bytes) -> list[tuple[str, str]]:
    """Split the regulations into articles ("B5.10 Formation Lap(s) Behind Safety Car")."""
    lines: list[str] = []
    for page in PdfReader(io.BytesIO(pdf_bytes)).pages:
        text = page.extract_text() or ""
        page_lines = text.splitlines()
        # Drop the repeated header block at the top of each page.
        i = 0
        while i < len(page_lines) and (
            not page_lines[i].strip() or PAGE_HEADER.match(page_lines[i].strip())
        ):
            i += 1
        lines += [ln.rstrip() for ln in page_lines[i:] if not HEADER_ANYWHERE.match(ln.strip())]
    sections: list[tuple[str, str]] = []
    label, body = None, []
    for ln in lines:
        m = ARTICLE.match(ln.strip())
        if m:
            if label and body:
                sections.append((label, "\n".join(body)))
            label, body = f"Article {m.group(1)} {m.group(2).strip()}", []
        elif label:
            body.append(ln)
    if label and body:
        sections.append((label, "\n".join(body)))
    # The table of contents repeats every heading with a page number and no body; keep the
    # longest copy of each article and drop near-empty ones.
    best: dict[str, tuple[str, str]] = {}
    for lbl, text in sections:
        article = lbl.split()[1]
        clean = re.sub(r"\s+\d+$", "", lbl)
        if len(text.strip()) >= MIN_SECTION_CHARS and len(text) > len(
            best.get(article, ("", ""))[1]
        ):
            best[article] = (clean, text)
    order = {a: i for i, (lbl, _) in enumerate(sections) for a in [lbl.split()[1]]}
    return sorted(best.values(), key=lambda st: order[st[0].split()[1]])


def latest_sporting_pdf(index_html: str, season: int) -> str | None:
    return latest_regulation_pdf(index_html, season, "B")


def fia_documents(fetcher: Fetcher, season: int) -> list[Document]:
    html = fetcher.get(FIA_INDEX, refresh=True).decode("utf-8", "replace")
    docs = []
    for letter in FIA_SECTIONS:
        doc = fia_document(fetcher, season, html, letter)
        if doc:
            docs.append(doc)
    return docs


def fia_document(fetcher: Fetcher, season: int, html: str, section: str = "B") -> Document | None:
    url = latest_regulation_pdf(html, season, section)
    name = FIA_SECTIONS[section]
    if not url:
        log.warning("no %s F1 %s PDF found on the FIA site", season, name)
        return None
    sections = regulation_sections(fetcher.get(url))
    issue = ISSUE.search(url.rsplit("/", 1)[-1])
    title = f"{season} F1 {name}" + (f", issue {int(issue.group(1))}" if issue else "")
    key = f"fia:{'sporting' if section == 'B' else 'section_' + section.lower()}:{season}"
    return Document("fia", key, title, url, sections, season=season)


# ---------------------------------------------------------------- Wikipedia

WIKI_HEADING = re.compile(r"^(={2,4})\s*(.+?)\s*\1\s*$")
SKIP_SECTIONS = {"References", "Notes", "External links", "See also", "Footnotes", "Citations"}
# Results tables arrive as flattened noise, and stats must come from our own data
# (query_stats), so classification and standings sections are not indexed.
SKIP_WORDS = ("classification", "standings", "results")


def wikipedia_sections(extract: str, lead: str = "Summary") -> list[tuple[str, str]]:
    sections: list[tuple[str, str]] = []
    label, body = lead, []
    for ln in extract.splitlines():
        m = WIKI_HEADING.match(ln.strip())
        if m:
            if body and label not in SKIP_SECTIONS:
                sections.append((label, "\n".join(body).strip()))
            label, body = m.group(2), []
        else:
            body.append(ln)
    if body and label not in SKIP_SECTIONS:
        sections.append((label, "\n".join(body).strip()))
    return [(s, t) for s, t in sections if t and not any(w in s.lower() for w in SKIP_WORDS)]


def wikipedia_document(
    fetcher: Fetcher, title: str, *, season: int | None, event_id: int | None = None
) -> Document | None:
    params = {
        "action": "query",
        "prop": "extracts|info",
        "inprop": "url",
        "explaintext": "1",
        "exsectionformat": "wiki",
        "redirects": "1",
        "format": "json",
        "formatversion": "2",
        "titles": title,
    }
    data = json.loads(fetcher.get(WIKI_API, params=params))
    page = (data.get("query", {}).get("pages") or [{}])[0]
    if page.get("missing") or not page.get("extract"):
        log.info("wikipedia: no article for %r", title)
        return None
    return Document(
        "wikipedia",
        f"wikipedia:{page['title'].replace(' ', '_')}",
        page["title"],
        page.get("fullurl"),
        wikipedia_sections(page["extract"]),
        season=season,
        event_id=event_id,
    )
